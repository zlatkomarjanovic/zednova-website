import { defineField, defineType } from "sanity";

export const portfolioCaseStudy = defineType({
  name: "portfolioCaseStudy",
  title: "Portfolio case study",
  type: "document",
  groups: [
    { name: "listing", title: "Listing & media", default: true },
    { name: "caseStudy", title: "Case study detail" },
    { name: "relationships", title: "Relationships" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      name: "title",
      type: "string",
      group: "listing",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "slug",
      type: "slug",
      group: "listing",
      options: { source: "title", maxLength: 96 },
      validation: (r) => r.required(),
    }),
    defineField({
      name: "client",
      type: "string",
      group: "listing",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "order",
      type: "number",
      title: "Display order",
      description: "Controls position in the homepage and /work grid (lower numbers appear first).",
      group: "listing",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "summary",
      type: "text",
      rows: 4,
      title: "Short summary",
      description: "Shown on portfolio cards in the homepage and /work grid.",
      group: "listing",
    }),
    defineField({
      name: "href",
      type: "url",
      title: "Live project URL",
      description: "External link for the portfolio card. Leave empty to link to the on-site case study page instead.",
      group: "listing",
    }),
    defineField({
      name: "coverImage",
      type: "image",
      title: "Cover image",
      group: "listing",
      options: { hotspot: true },
      fields: [
        defineField({
          name: "alt",
          type: "string",
          title: "Alt text",
          validation: (r) =>
            r.min(1).warning("Cover alt text improves SEO and accessibility"),
        }),
        defineField({ name: "caption", type: "string", title: "Caption" }),
      ],
    }),
    defineField({
      name: "imageAlt",
      type: "string",
      title: "Cover alt override",
      description: "Optional override when cover image alt should differ from the asset alt field.",
      group: "listing",
    }),
    defineField({
      name: "videoUrl",
      type: "string",
      title: "Video URL",
      description: "Absolute URL or site-relative path (e.g. /assets/portfolio/videos/demo.mp4).",
      group: "listing",
    }),
    defineField({
      name: "logo",
      type: "portfolioLogo",
      title: "Client logo",
      group: "listing",
    }),
    defineField({
      name: "accent",
      type: "string",
      group: "listing",
      initialValue: "#1c1917",
    }),
    defineField({
      name: "category",
      type: "string",
      group: "listing",
      options: {
        list: [
          "Websites",
          "SaaS",
          "Real estate",
          "Nonprofit",
          "Ecommerce",
          "Healthcare",
          "Automation",
        ],
      },
    }),
    defineField({ name: "year", type: "number", group: "listing" }),
    defineField({
      name: "featured",
      type: "boolean",
      title: "Featured case study",
      description: "Featured items can surface in structured data and related modules.",
      group: "listing",
      initialValue: false,
    }),

    defineField({
      name: "resultHeadline",
      type: "string",
      title: "Result headline",
      description: "Primary outcome line on the case study detail page.",
      group: "caseStudy",
    }),
    defineField({ name: "timeline", type: "string", group: "caseStudy" }),
    defineField({ name: "challenge", type: "text", rows: 5, group: "caseStudy" }),
    defineField({
      name: "solution",
      type: "array",
      title: "Solution (paragraphs)",
      group: "caseStudy",
      of: [{ type: "text", rows: 3 }],
    }),
    defineField({
      name: "results",
      type: "array",
      group: "caseStudy",
      of: [{ type: "stat" }],
    }),
    defineField({
      name: "techStack",
      type: "array",
      title: "Tools used",
      group: "caseStudy",
      of: [{ type: "string" }],
    }),
    defineField({
      name: "workflow",
      type: "array",
      title: "Workflow",
      group: "caseStudy",
      of: [{ type: "workflowStep" }],
    }),
    defineField({
      name: "timelinePhases",
      type: "array",
      title: "Timeline phases",
      group: "caseStudy",
      of: [{ type: "timelinePhase" }],
    }),
    defineField({
      name: "screenshots",
      type: "array",
      title: "Screenshots",
      group: "caseStudy",
      of: [{ type: "caseStudyScreenshot" }],
    }),
    defineField({
      name: "testimonial",
      type: "reference",
      to: [{ type: "testimonial" }],
      group: "caseStudy",
    }),
    defineField({
      name: "faqs",
      type: "array",
      title: "FAQ",
      group: "caseStudy",
      of: [{ type: "articleFaq" }],
    }),

    defineField({
      name: "industry",
      type: "reference",
      title: "Primary industry",
      to: [{ type: "industry" }, { type: "industryParent" }],
      group: "relationships",
    }),
    defineField({
      name: "servicesUsed",
      type: "array",
      title: "Services used",
      group: "relationships",
      of: [{ type: "reference", to: [{ type: "service" }] }],
    }),
    defineField({
      name: "relatedIndustries",
      type: "array",
      title: "Related industries",
      group: "relationships",
      of: [{ type: "reference", to: [{ type: "industry" }, { type: "industryParent" }] }],
    }),
    defineField({
      name: "relatedCaseStudies",
      type: "array",
      title: "Related work",
      group: "relationships",
      of: [{ type: "reference", to: [{ type: "portfolioCaseStudy" }] }],
    }),
    defineField({
      name: "relatedInsights",
      type: "array",
      group: "relationships",
      of: [{ type: "reference", to: [{ type: "post" }] }],
    }),
    defineField({ name: "seo", type: "seoFields", group: "seo" }),
  ],
  orderings: [{ title: "Display order", name: "orderAsc", by: [{ field: "order", direction: "asc" }] }],
  preview: {
    select: { title: "title", subtitle: "client", media: "coverImage", order: "order" },
    prepare({ title, subtitle, media, order }) {
      return {
        title,
        subtitle: order != null ? `#${order} · ${subtitle ?? ""}` : subtitle,
        media,
      };
    },
  },
});
